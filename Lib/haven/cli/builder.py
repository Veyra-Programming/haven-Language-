"""
Haven Language Bytecode Compiler & Package Builder
Compiles .hvn source files into tamper-proof bytecode artifacts (.hvc) with cryptographic SHA-256 manifests.
Standard Specification & Architecture by Anirudha Puthraya.
"""

import sys
import os
import marshal
import hashlib
import time
from .colors import green, yellow, red, cyan, bold, dim


def build_file(file_path: str, output_path: str = None) -> int:
    """Compiles a Haven source file into an optimized .hvc bytecode file."""
    if not os.path.exists(file_path):
        print(f"{bold(red('Error:'))} Source file '{file_path}' does not exist.", file=sys.stderr)
        return 1

    print(f"\n{bold(cyan('Haven Bytecode Compiler (haven build)'))}")
    print(f"[*] Reading source: {file_path}")

    try:
        with open(file_path, "r", encoding="utf-8") as f:
            src = f.read()

        src_hash = hashlib.sha256(src.encode("utf-8")).hexdigest()

        t0 = time.perf_counter()
        # Compile using native Haven VM
        code_obj = compile(src, file_path, "exec", optimize=1)
        dur = (time.perf_counter() - t0) * 1000

        # Determine output .hvc file
        if not output_path:
            base, _ = os.path.splitext(file_path)
            output_path = base + ".hvc"

        # Write serialized bytecode
        header = b"HVN\x01" + int(time.time()).to_bytes(4, "little")
        with open(output_path, "wb") as f:
            f.write(header)
            marshal.dump(code_obj, f)

        with open(output_path, "rb") as f:
            bin_data = f.read()
        bin_hash = hashlib.sha256(bin_data).hexdigest()

        # Write cryptographic manifest
        manifest_path = output_path + ".manifest"
        manifest_text = f"""# Haven Cryptographic Bytecode Manifest
# Generated by Haven Compiler v1.0.0
source_file = {os.path.basename(file_path)}
source_sha256 = {src_hash}
bytecode_file = {os.path.basename(output_path)}
bytecode_sha256 = {bin_hash}
build_timestamp = {int(time.time())}
standard = ODCS-1.0.0
author = Anirudha Puthraya
"""
        with open(manifest_path, "w", encoding="utf-8") as f:
            f.write(manifest_text)

        print(f"{bold(green('✔ Successfully compiled'))} in {dur:.2f}ms")
        print(f"  • Source SHA-256    : {dim(src_hash[:32])}...")
        print(f"  • Bytecode Output   : {bold(output_path)} ({len(bin_data)} bytes)")
        print(f"  • Bytecode SHA-256  : {dim(bin_hash[:32])}...")
        print(f"  • Integrity Manifest: {manifest_path}\n")
        return 0

    except Exception as e:
        print(f"{bold(red('Build Error:'))} Failed to compile '{file_path}': {e}", file=sys.stderr)
        return 1
